import asyncio
import contextlib
import os
from abc import ABC, abstractmethod
from collections.abc import AsyncIterator, Sequence
from functools import lru_cache
from pathlib import Path

from app.core.config import Settings, get_settings

READ_CHUNK_SIZE = 1024 * 1024  # 1 MB


class StorageError(Exception):
    """The storage service failed or couldn't be reached. The message is
    fixed and safe to show; details (never credentials) are logged."""

    def __init__(self, message: str = "File storage is unavailable; please try again later"):
        super().__init__(message)


class StorageBackend(ABC):
    """Where uploaded file bytes live. Swap implementations (local disk, S3, ...)
    without touching the rest of the app.

    Keys are opaque strings generated by the app ("{owner_id}/{document_id}").
    Never build a key from user input.
    """

    @abstractmethod
    async def save(self, key: str, chunks: AsyncIterator[bytes]) -> int:
        """Write the stream under `key` and return the number of bytes written.

        If the stream raises or anything fails midway, no data may remain
        under `key`.
        """

    @abstractmethod
    async def open(self, key: str) -> AsyncIterator[bytes]:
        """Return an async iterator over the file's bytes.

        Raises FileNotFoundError immediately (before iteration) if the key is missing.
        """

    @abstractmethod
    async def delete(self, key: str) -> None:
        """Remove the file. Silently succeeds if it is already gone."""

    async def delete_many(self, keys: Sequence[str]) -> None:
        """Remove several files (a collection's, an account's). Backends that
        can delete in bulk do it in fewer requests."""
        for key in keys:
            await self.delete(key)


class LocalStorageBackend(StorageBackend):
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        # Defense in depth: keys are generated by us, but if one ever contained
        # "../" this refuses to touch anything outside the storage root.
        if not path.is_relative_to(self.root) or path == self.root:
            raise ValueError("Invalid storage key")
        return path

    async def save(self, key: str, chunks: AsyncIterator[bytes]) -> int:
        path = self._path(key)
        # Write under a temporary name and rename on success, so a file with the
        # final name is always complete.
        partial = path.with_name(path.name + ".part")
        await asyncio.to_thread(partial.parent.mkdir, parents=True, exist_ok=True)
        written = 0
        try:
            with partial.open("wb") as f:
                async for chunk in chunks:
                    # Disk writes block, so run them off the event loop.
                    await asyncio.to_thread(f.write, chunk)
                    written += len(chunk)
            await asyncio.to_thread(os.replace, partial, path)
        except BaseException:
            # Includes size-limit rejections raised by the stream and request
            # cancellation: never leave a partial file behind.
            with contextlib.suppress(FileNotFoundError):
                partial.unlink()
            raise
        return written

    async def open(self, key: str) -> AsyncIterator[bytes]:
        path = self._path(key)
        f = await asyncio.to_thread(path.open, "rb")  # raises FileNotFoundError now

        async def iterate() -> AsyncIterator[bytes]:
            try:
                while chunk := await asyncio.to_thread(f.read, READ_CHUNK_SIZE):
                    yield chunk
            finally:
                f.close()

        return iterate()

    async def delete(self, key: str) -> None:
        path = self._path(key)
        with contextlib.suppress(FileNotFoundError):
            await asyncio.to_thread(path.unlink)


def get_storage() -> StorageBackend:
    """FastAPI dependency: the backend chosen by STORAGE_BACKEND. Reads the
    settings on each call so tests can redirect them."""
    settings = get_settings()
    if settings.STORAGE_BACKEND == "s3":
        return _s3_backend(*_s3_config(settings))
    return LocalStorageBackend(settings.STORAGE_PATH)


def _s3_config(settings: Settings) -> tuple[str, str, str, str, str]:
    return (
        settings.S3_ENDPOINT_URL,
        settings.S3_BUCKET,
        settings.S3_ACCESS_KEY_ID.get_secret_value(),
        settings.S3_SECRET_ACCESS_KEY.get_secret_value(),
        settings.S3_REGION,
    )


@lru_cache(maxsize=1)
def _s3_backend(
    endpoint_url: str, bucket: str, access_key_id: str, secret_access_key: str, region: str
) -> StorageBackend:
    """One client per configuration: creating a boto3 client is slow and
    takes several MB, and the client is safe to share between threads."""
    from app.services.s3_storage import S3StorageBackend, make_client

    client = make_client(endpoint_url, access_key_id, secret_access_key, region)
    return S3StorageBackend(client, bucket)
