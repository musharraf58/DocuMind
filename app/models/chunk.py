import uuid
from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import Computed, DateTime, ForeignKey, Index, Integer, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base

# Size of the chunks.embedding column. A pgvector column holds vectors of
# exactly one size, so this is fixed by migration 0005 and must equal the
# EMBEDDING_DIMENSIONS setting (checked in get_embedding_provider).
EMBEDDING_COLUMN_DIMENSIONS = 1024

# The text search configuration the keyword column is built with (migration
# 0009). Like the embedding size, it's part of the schema: changing it needs
# a migration. Other configurations can still be searched, computed on the fly.
INDEXED_TEXT_SEARCH_CONFIG = "english"


class Chunk(Base):
    """A piece of a document's extracted text, small enough to embed and retrieve."""

    __tablename__ = "chunks"
    __table_args__ = (
        # Also serves as the index for "chunks of document X" lookups, since
        # document_id is its first column; a separate document_id index would
        # be redundant.
        UniqueConstraint("document_id", "chunk_index", name="uq_chunks_document_index"),
        # Approximate nearest-neighbour index for cosine distance. The operator
        # class must match the operator queries use: vector_cosine_ops serves
        # "<=>" only; an "<->" (L2) query would ignore this index.
        # Keyword search: an inverted index over each chunk's words.
        Index("ix_chunks_search_vector", "search_vector", postgresql_using="gin"),
        Index(
            "ix_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    # All three cascade, so deleting a document, collection or user removes
    # its chunks in the database without the app loading them.
    document_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("documents.id", ondelete="CASCADE"))
    owner_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    # Indexed so a collection delete can find chunks to cascade without a full
    # table scan; Phase 4 search filters by collection too.
    collection_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("collections.id", ondelete="CASCADE"), index=True
    )
    chunk_index: Mapped[int] = mapped_column(Integer)
    content: Mapped[str] = mapped_column(Text)
    page_number: Mapped[int | None] = mapped_column(Integer, default=None)
    section_title: Mapped[str | None] = mapped_column(Text, default=None)
    token_count: Mapped[int] = mapped_column(Integer)
    # NULL for chunks made before embeddings existed (Phase 3); they are left
    # out of search until their document is processed again.
    embedding: Mapped[list[float] | None] = mapped_column(
        Vector(EMBEDDING_COLUMN_DIMENSIONS), default=None
    )
    # Which model made the vector. Vectors from different models live in
    # different spaces, so search only compares vectors from the current model.
    embedding_model: Mapped[str | None] = mapped_column(Text, default=None)
    # Words of the section title and content, normalized for keyword search.
    # Generated by Postgres on every insert or update, so re-processing a
    # document (new chunks) can never leave it out of date.
    search_vector: Mapped[str] = mapped_column(
        TSVECTOR,
        Computed(
            f"to_tsvector('{INDEXED_TEXT_SEARCH_CONFIG}'::regconfig, "
            "coalesce(section_title, '') || ' ' || content)",
            persisted=True,
        ),
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
